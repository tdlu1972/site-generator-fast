// Writes nfkd.h, the table site.c slugs non-ASCII text by: for each code point of the ranges below, what makefun-site's
// slug rule reads from it once NFKD has decomposed it and its combining marks (\p{M}) are dropped, spelled for the
// slug: an ASCII letter or digit (A-Z lowered) for each such character and "-" for every other one, "" for nothing.
// NFKD decomposes a string character by character (its reordering moves only marks, which are dropped), so the slug
// of a text is read from its characters' entries in order. A code point outside these ranges goes to JavaScript.
// The ranges are blocks assigned long before node22's Unicode, so any node writes the same table: node gen-nfkd.mjs > nfkd.h
const RANGES = [[0x80, 0x250], [0x300, 0x500], [0x2000, 0x2070], [0x3000, 0x3100], [0xfb00, 0xfb50], [0xff00, 0xfff0]];
const spell = (cp) => {
  const plain = String.fromCodePoint(cp).normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  for (const ch of plain) out += /[A-Za-z0-9]/.test(ch) ? ch.toLowerCase() : '-';
  return out;
};
let pool = '';
const lines = [];
for (const [a, b] of RANGES) {
  const offs = [];
  for (let cp = a; cp < b; cp++) {
    const s = spell(cp);
    if (s.length > 15) throw new Error(`U+${cp.toString(16)} spells ${s.length} characters`);
    let at = pool.indexOf(s);
    if (s === '') at = 0;
    else if (at === -1) {
      at = pool.length;
      pool += s;
    }
    if (at >= 4096) throw new Error('pool past 4096');
    offs.push((at << 4) | s.length);
  }
  lines.push(`static const unsigned short NFKD_${a.toString(16)}[${b - a}] = {${offs.join(',')}};`);
}
console.log(`// Generated by gen-nfkd.mjs (node ${process.version}): what NFKD leaves of each code point, for slugs.`);
console.log(`static const char NFKD_POOL[] = ${JSON.stringify(pool)};`);
for (const l of lines) console.log(l);
console.log(`static const unsigned int NFKD_RANGES[${RANGES.length}][2] = {${RANGES.map(([a, b]) => `{${a}, ${b}}`).join(', ')}};`);
console.log(`static const unsigned short *const NFKD_TABLES[${RANGES.length}] = {${RANGES.map(([a]) => `NFKD_${a.toString(16)}`).join(', ')}};`);
